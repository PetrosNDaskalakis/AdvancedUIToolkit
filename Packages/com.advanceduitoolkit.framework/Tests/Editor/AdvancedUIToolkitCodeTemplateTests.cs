using System;
using System.Collections.Generic;
using System.IO;
using NUnit.Framework;
using UnityEngine.UI;
using AdvancedUIToolkit.Editor;

namespace AdvancedUIToolkit.Tests
{
    /// <summary>Tests documented binding generation and opt-in authoring templates.</summary>
    public sealed class AdvancedUIToolkitCodeTemplateTests
    {
        /// <summary>Ensures the default generator documents class members and caches references.</summary>
        [Test]
        public void DefaultGeneratorAddsXmlDocumentation()
        {
            var entries = new List<UIBindingRoot.Entry>
            {
                new UIBindingRoot.Entry
                {
                    Key = "Fire", HierarchyKey = "Fire", ComponentType = typeof(Button).FullName
                }
            };

            string source = AdvancedUIToolkitCodeTemplate.Generate("WeaponBindings", "Game.UI", entries, null);

            StringAssert.Contains("// <auto-generated />", source);
            StringAssert.Contains("public sealed class WeaponBindings : IUIBindings", source);
            StringAssert.Contains("/// <summary>Cached reference to Fire UI component.</summary>", source);
            StringAssert.Contains("public UnityEngine.UI.Button Fire { get; private set; }", source);
            StringAssert.Contains("Fire = root.Get<UnityEngine.UI.Button>(\"Fire\");", source);
        }

        /// <summary>Ensures developer-defined formatting survives a template-based generation.</summary>
        [Test]
        public void ExampleScriptControlsGeneratedStructure()
        {
            string path = "Assets/__AdvancedUIToolkitCodeTemplateTests_" + Guid.NewGuid().ToString("N") + ".cs";
            try
            {
                File.WriteAllText(path,
                    "using AdvancedUIToolkit;\nnamespace My.Example\n{\n" +
                    "    /// <summary>Example</summary>\n" +
                    "    public sealed class ExampleScript : IUIBindings\n    {\n" +
                    "        // <ADVANCEDUITOOLKIT:PROPERTIES>\n" +
                    "        /// <summary>Initialize refs.</summary>\n" +
                    "        public void Initialize(UIBindingRoot root)\n        {\n" +
                    "            // <ADVANCEDUITOOLKIT:ASSIGNMENTS>\n        }\n    }\n}\n");

                string error;
                Assert.IsTrue(AdvancedUIToolkitCodeTemplate.Validate(path, out error), error);
                string output = AdvancedUIToolkitCodeTemplate.Generate("SonarBindings", "Test.Sonar",
                    new[] { new UIBindingRoot.Entry
                    {
                        Key = "Track", HierarchyKey = "Track", ComponentType = typeof(Button).FullName
                    } }, path);

                StringAssert.Contains("namespace Test.Sonar", output);
                StringAssert.Contains("class SonarBindings : IUIBindings", output);
                StringAssert.Contains("/// <summary>Initialize refs.</summary>", output);
                StringAssert.Contains("public UnityEngine.UI.Button Track", output);
                StringAssert.Contains("Track = root.Get<UnityEngine.UI.Button>(\"Track\");", output);
                Assert.IsFalse(output.Contains("// <ADVANCEDUITOOLKIT:PROPERTIES>"));
            }
            finally
            {
                if (File.Exists(path)) File.Delete(path);
            }
        }

        /// <summary>Confirms that templates missing an insertion marker are rejected.</summary>
        [Test]
        public void InvalidTemplateIsRejected()
        {
            string path = "Assets/__AdvancedUIToolkitInvalidTemplate_" + Guid.NewGuid().ToString("N") + ".cs";
            try
            {
                File.WriteAllText(path,
                    "namespace My.Example { public class ExampleScript : AdvancedUIToolkit.IUIBindings" +
                    " { public void Initialize(AdvancedUIToolkit.UIBindingRoot root) {} } }");
                string error;
                Assert.IsFalse(AdvancedUIToolkitCodeTemplate.Validate(path, out error));
                StringAssert.Contains("marker", error);
            }
            finally
            {
                if (File.Exists(path)) File.Delete(path);
            }
        }
    }
}
