using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace AdvancedUIToolkit.Editor
{
    /// <summary>
    /// Creates documented C# binding classes from a safe, explicitly marked example script.
    /// A selected example must compile as ordinary C# before generation.
    /// </summary>
    internal static class AdvancedUIToolkitCodeTemplate
    {
        /// <summary>Editor preference storing the default template's Unity asset GUID.</summary>
        private const string DefaultTemplateGuidPref = "AdvancedUIToolkit.Generation.DefaultTemplateGuid";

        /// <summary>Gets the optional default C# template used for new binding roots.</summary>
        /// <returns>The template script, or null if no default is registered.</returns>
        internal static MonoScript GetDefaultTemplate()
        {
            string guid = EditorPrefs.GetString(DefaultTemplateGuidPref, string.Empty);
            if (string.IsNullOrEmpty(guid)) return null;
            string path = AssetDatabase.GUIDToAssetPath(guid);
            return string.IsNullOrEmpty(path) ? null : AssetDatabase.LoadAssetAtPath<MonoScript>(path);
        }

        /// <summary>Sets the default generation style for subsequently configured UI roots.</summary>
        /// <param name="script">Valid template asset, or null to clear the default.</param>
        internal static void SetDefaultTemplate(MonoScript script)
        {
            string path = script != null ? AssetDatabase.GetAssetPath(script) : string.Empty;
            string error;
            if (!Validate(path, out error))
                throw new InvalidOperationException("Cannot set the default template: " + error);
            EditorPrefs.SetString(DefaultTemplateGuidPref,
                string.IsNullOrEmpty(path) ? string.Empty : AssetDatabase.AssetPathToGUID(path));
        }

        /// <summary>Marker for inserting generated accessor properties.</summary>
        private const string PropertyMarker = "// <ADVANCEDUITOOLKIT:PROPERTIES>";

        /// <summary>Marker for inserting the component initialization statements.</summary>
        private const string AssignmentMarker = "// <ADVANCEDUITOOLKIT:ASSIGNMENTS>";

        /// <summary>Optional template comment configuring generated property XML summaries.</summary>
        private static readonly Regex PropertyDocumentationPattern = new Regex(
            @"(?m)^[ \t]*// <ADVANCEDUITOOLKIT:PROPERTY_DOC>[ \t]*(?<format>[^\r\n]*)\r?$",
            RegexOptions.CultureInvariant);

        /// <summary>Default XML summary pattern; identical to the v0.9.5 output.</summary>
        private const string DefaultPropertyDocumentation = "Cached reference to {hierarchy} UI component.";

        /// <summary>Expected header used to prevent overwriting developer-authored files.</summary>
        private const string GeneratedHeader = "// <auto-generated />";

        /// <summary>Locates a namespace declaration in the user-provided class.</summary>
        private static readonly Regex NamespacePattern = new Regex(
            @"\bnamespace\s+([A-Za-z_][A-Za-z_0-9]*(?:\.[A-Za-z_][A-Za-z_0-9]*)*)\s*(?=\{|;)",
            RegexOptions.CultureInvariant);

        /// <summary>Locates the single class whose name will be replaced.</summary>
        private static readonly Regex ClassPattern = new Regex(
            @"\bclass\s+([A-Za-z_][A-Za-z_0-9]*)\s*:\s*(?:AdvancedUIToolkit\.)?IUIBindings\b",
            RegexOptions.CultureInvariant);

        /// <summary>Matches a standalone marker line and retains the desired indentation.</summary>
        private static Regex MarkerPattern(string marker)
        {
            return new Regex(@"(?m)^(?<indent>[ \t]*)" + Regex.Escape(marker) + @"[ \t]*$",
                RegexOptions.CultureInvariant);
        }

        /// <summary>Checks a selected template file before allowing generation.</summary>
        /// <param name="path">Project-relative path to a C# example script.</param>
        /// <param name="error">Human-readable explanation of an invalid template.</param>
        /// <returns>True if the template has the required declarations and insertion markers.</returns>
        internal static bool Validate(string path, out string error)
        {
            error = null;
            if (string.IsNullOrEmpty(path)) return true;
            if (!path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) ||
                !(path.StartsWith("Assets/", StringComparison.Ordinal) ||
                  path.StartsWith("Packages/", StringComparison.Ordinal)))
            {
                error = "Select a C# script asset inside Assets or Packages.";
                return false;
            }

            if (!File.Exists(path))
            {
                error = "Script file does not exist: " + path;
                return false;
            }

            string source = File.ReadAllText(path);
            if (source.StartsWith(GeneratedHeader, StringComparison.Ordinal))
            {
                error = "Generated binding files cannot be used as authoring templates.";
                return false;
            }

            if (NamespacePattern.Matches(source).Count != 1 || ClassPattern.Matches(source).Count != 1)
            {
                error = "Template needs exactly one namespace and one class implementing IUIBindings.";
                return false;
            }

            if (MarkerPattern(PropertyMarker).Matches(source).Count != 1 ||
                MarkerPattern(AssignmentMarker).Matches(source).Count != 1)
            {
                error = "Add exactly one // <ADVANCEDUITOOLKIT:PROPERTIES> and one " +
                    "// <ADVANCEDUITOOLKIT:ASSIGNMENTS> marker on their own lines.";
                return false;
            }

            MatchCollection documentation = PropertyDocumentationPattern.Matches(source);
            if (documentation.Count > 1 || (documentation.Count == 1 &&
                string.IsNullOrWhiteSpace(documentation[0].Groups["format"].Value)))
            {
                error = "Use at most one nonempty // <ADVANCEDUITOOLKIT:PROPERTY_DOC> directive.";
                return false;
            }

            int propertyIndex = source.IndexOf(PropertyMarker, StringComparison.Ordinal);
            int assignmentIndex = source.IndexOf(AssignmentMarker, StringComparison.Ordinal);
            if (propertyIndex >= assignmentIndex)
            {
                error = "The properties marker must appear before the assignments marker.";
                return false;
            }

            if (!Regex.IsMatch(source, @"\bvoid\s+Initialize\s*\(\s*(?:AdvancedUIToolkit\.)?UIBindingRoot\s+root\s*\)",
                RegexOptions.CultureInvariant))
            {
                error = "Template needs public void Initialize(UIBindingRoot root).";
                return false;
            }

            return true;
        }

        /// <summary>Generates the complete documented bindings source file.</summary>
        /// <param name="className">Generated class identifier.</param>
        /// <param name="namespaceName">Generated class namespace.</param>
        /// <param name="entries">Serialized references to expose in the binding class.</param>
        /// <param name="templatePath">Optional path to the developer's ExampleScript.cs.</param>
        /// <returns>Fully formatted C# source with an auto-generated header.</returns>
        internal static string Generate(string className, string namespaceName,
            IEnumerable<UIBindingRoot.Entry> entries, string templatePath)
        {
            if (className == null) throw new ArgumentNullException(nameof(className));
            if (namespaceName == null) throw new ArgumentNullException(nameof(namespaceName));
            if (entries == null) throw new ArgumentNullException(nameof(entries));

            var manifest = entries.OrderBy(entry => entry.Key, StringComparer.Ordinal).ToList();
            if (string.IsNullOrEmpty(templatePath))
                return GenerateDefault(className, namespaceName, manifest);

            string error;
            if (!Validate(templatePath, out error))
                throw new InvalidOperationException("Invalid Advanced UI Toolkit code template: " + error);

            string source = File.ReadAllText(templatePath).Replace("\r\n", "\n").Replace("\r", "\n");
            Match documentation = PropertyDocumentationPattern.Match(source);
            string propertyDocumentation = documentation.Success
                ? documentation.Groups["format"].Value.Trim()
                : DefaultPropertyDocumentation;
            if (documentation.Success)
                source = PropertyDocumentationPattern.Replace(source, string.Empty, 1);
            source = NamespacePattern.Replace(source, "namespace " + namespaceName, 1);
            source = ClassPattern.Replace(source, match => match.Value.Replace(
                match.Groups[1].Value, className), 1);
            source = MarkerPattern(PropertyMarker).Replace(source, match =>
                FormatProperties(manifest, match.Groups["indent"].Value, propertyDocumentation), 1);
            source = MarkerPattern(AssignmentMarker).Replace(source, match =>
                FormatAssignments(manifest, match.Groups["indent"].Value), 1);
            return GeneratedHeader + "\n" + source.TrimStart('\n').TrimEnd('\n') + "\n";
        }

        /// <summary>Generates the standard well-documented binding class.</summary>
        /// <param name="className">Class name requested by the developer.</param>
        /// <param name="namespaceName">Namespace requested by the developer.</param>
        /// <param name="manifest">Validated, sorted bindings.</param>
        /// <returns>Default C# source code.</returns>
        private static string GenerateDefault(string className, string namespaceName,
            List<UIBindingRoot.Entry> manifest)
        {
            var builder = new StringBuilder();
            builder.AppendLine(GeneratedHeader);
            builder.AppendLine("using System;");
            builder.AppendLine("using AdvancedUIToolkit;");
            builder.AppendLine();
            builder.AppendLine("namespace " + namespaceName);
            builder.AppendLine("{");
            builder.AppendLine("    /// <summary>");
            builder.AppendLine("    /// Strongly typed, cached component references for this UI root.");
            builder.AppendLine("    /// </summary>");
            builder.AppendLine("    public sealed class " + className + " : IUIBindings");
            builder.AppendLine("    {");
            builder.Append(FormatProperties(manifest, "        "));
            builder.AppendLine();
            builder.AppendLine("        /// <summary>Resolves all references from the root's saved manifest.</summary>");
            builder.AppendLine("        /// <param name=\"root\">Root containing the serialized UI references.</param>");
            builder.AppendLine("        public void Initialize(UIBindingRoot root)");
            builder.AppendLine("        {");
            builder.AppendLine("            if (root == null) throw new ArgumentNullException(nameof(root));");
            builder.Append(FormatAssignments(manifest, "            "));
            builder.AppendLine("        }");
            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        /// <summary>Formats each generated accessor with XML documentation.</summary>
        /// <param name="manifest">Validated binding references.</param>
        /// <param name="indent">Whitespace matching the surrounding template.</param>
        /// <returns>Accessor declarations ending in newlines.</returns>
        private static string FormatProperties(List<UIBindingRoot.Entry> manifest, string indent,
            string documentation = DefaultPropertyDocumentation)
        {
            var builder = new StringBuilder();
            foreach (var entry in manifest)
            {
                string summary = documentation.Replace("{name}", entry.Key ?? string.Empty)
                    .Replace("{hierarchy}", entry.HierarchyKey ?? entry.Key ?? string.Empty)
                    .Replace("{type}", entry.ComponentType ?? string.Empty);
                builder.Append(indent).Append("/// <summary>")
                    .Append(EscapeXml(summary)).AppendLine("</summary>");
                builder.Append(indent).Append("public ").Append(entry.ComponentType).Append(' ')
                    .Append(entry.Key).AppendLine(" { get; private set; }");
                builder.AppendLine();
            }
            return builder.ToString();
        }

        /// <summary>Escapes user-authored UI names for XML documentation without changing C# identifiers.</summary>
        /// <param name="value">Description that may contain XML punctuation.</param>
        /// <returns>Text suitable for an XML comment summary.</returns>
        private static string EscapeXml(string value)
        {
            return (value ?? string.Empty).Replace("&", "&amp;").Replace("<", "&lt;")
                .Replace(">", "&gt;").Replace("\"", "&quot;").Replace("'", "&apos;");
        }

        /// <summary>Formats manifest lookups using strong component types.</summary>
        /// <param name="manifest">Validated binding references.</param>
        /// <param name="indent">Whitespace matching the surrounding template.</param>
        /// <returns>Reference assignments ending in newlines.</returns>
        private static string FormatAssignments(List<UIBindingRoot.Entry> manifest, string indent)
        {
            var builder = new StringBuilder();
            foreach (var entry in manifest)
                builder.Append(indent).Append(entry.Key).Append(" = root.Get<")
                    .Append(entry.ComponentType).Append(">(\"").Append(entry.Key).AppendLine("\");");
            return builder.ToString();
        }
    }
}
