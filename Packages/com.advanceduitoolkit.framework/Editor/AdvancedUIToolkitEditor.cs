    /// <summary>
    /// Editor-only binding discovery, rename preview, validation and C# generation.
    /// No new component has to be attached to individual buttons or labels.
    /// </summary>
    internal enum UIAutoGenerationStatus
    {
        /// <summary>Indicates the UpToDate generation state.</summary>
        UpToDate,
        /// <summary>Indicates the SafeChange generation state.</summary>
        SafeChange,
        /// <summary>Previously generated accessors are missing from the hierarchy and await removal.</summary>
        PendingRemoval,
        /// <summary>Indicates the Generated generation state.</summary>
        Generated,
        /// <summary>Indicates the SetupRequired generation state.</summary>
        SetupRequired,
        /// <summary>Indicates the Blocked generation state.</summary>
        Blocked
    }

