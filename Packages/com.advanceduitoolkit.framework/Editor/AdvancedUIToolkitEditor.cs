        // Unity sends this when the Hierarchy changes, including many rename/reparent events.
        // Only rescan when a bindable element actually changed. Don't overwrite a manual
        // public-API edit that hasn't been generated yet.
        /// <summary>Performs the workspace hierarchy changed operation.</summary>
        internal void WorkspaceHierarchyChanged()
        {
            if (target == null || scanFingerprint == null) return;
            if (string.Equals(scanFingerprint, GetFingerprint(), StringComparison.Ordinal)) return;

            // A new or duplicated prefab must not freeze Binder just because another
            // property has a staged name/XML edit. Reconcile by Component identity so
            // the user's unpublished changes survive the hierarchy rescan.
            Scan(true);
            Repaint();
        }

        /// <summary>Draws the binding page inside the consolidated workspace.</summary>
        internal void DrawWorkspacePage()
        {
            EditorGUILayout.LabelField("Advanced UI Toolkit / AutoBinder + Rename Assistant", EditorStyles.boldLabel);

            GameObject selected = (GameObject)EditorGUILayout.ObjectField("UI Root", target, typeof(GameObject), true);
            if (selected != target)
            {
                SetTarget(selected);
            }

            if (GUILayout.Button("Use Selection"))
            {
                SetTarget(Selection.activeGameObject);
            }

            bool nextPreserve = EditorGUILayout.ToggleLeft(
                "Preserve generated property names when UI objects are renamed", preserveExistingApi);
            if (nextPreserve != preserveExistingApi)
            {
                preserveExistingApi = nextPreserve;
                EditorPrefs.SetBool(PreservePref, preserveExistingApi);
                // Re-evaluate the preview against saved manifest entries.
                Scan();
            }

            if (GUILayout.Button("Scan & Preview Changes")) Scan();

            EditorGUILayout.Space();
            EditorGUILayout.LabelField(
                $"Found: {candidates.Count}   Removed: {removed.Count}   Errors: {errors.Count}",
                EditorStyles.boldLabel);

            scroll = EditorGUILayout.BeginScrollView(scroll);
            foreach (string error in errors) EditorGUILayout.HelpBox(error, MessageType.Error);
            foreach (string warning in warnings) EditorGUILayout.HelpBox(warning, MessageType.Warning);

            if (candidates.Count > 0)
            {
                EditorGUILayout.LabelField("Binding Preview", EditorStyles.boldLabel);
                foreach (BindingCandidate candidate in candidates)
                {
                    EditorGUILayout.BeginVertical(EditorStyles.helpBox);
                    EditorGUILayout.LabelField(
                        candidate.Reference != null ? candidate.Reference.gameObject.name : "Missing component",
                        EditorStyles.boldLabel);
                    using (new EditorGUI.DisabledScope(true))
                        EditorGUILayout.ObjectField("Component", candidate.Reference, typeof(Component), true);

                    EditorGUILayout.LabelField("Name key", candidate.HierarchyKey);
                    if (!string.IsNullOrEmpty(candidate.PreviousKey))
                        EditorGUILayout.LabelField("Previous API", candidate.PreviousKey);

                    string nextSummary = EditorGUILayout.TextField("XML Summary",
                        candidate.XmlSummary ?? string.Empty);
                    string nextKey = EditorGUILayout.TextField("Generated API", candidate.ApiKey);
                    if (nextSummary != candidate.XmlSummary || nextKey != candidate.ApiKey)
                        UpdateWorkspaceProperty(candidate.Reference, nextSummary, nextKey);
                    EditorGUILayout.LabelField("Change", Describe(candidate));
                    EditorGUILayout.EndVertical();
                }
            }

            if (removed.Count > 0)
            {
                EditorGUILayout.Space();
                EditorGUILayout.LabelField("Bindings no longer found", EditorStyles.boldLabel);
                foreach (UIBindingRoot.Entry entry in removed)
                    EditorGUILayout.HelpBox(
                        $"Removed: {entry.Key} ({entry.ComponentType}). " +
                        "Its generated accessor will be deleted if you generate.", MessageType.Warning);
            }
            EditorGUILayout.EndScrollView();

            EditorGUILayout.Space();
            className = EditorGUILayout.TextField("Class Name", className);
            namespaceName = EditorGUILayout.TextField("Namespace", namespaceName);
            outputFolder = EditorGUILayout.TextField("Output Folder", outputFolder);
            using (new EditorGUILayout.HorizontalScope())
            {
                exampleScript = (MonoScript)EditorGUILayout.ObjectField(
                    new GUIContent("Example Script", "Optional C# source template, remembered per root."),
                    exampleScript, typeof(MonoScript), false);
                using (new EditorGUI.DisabledScope(exampleScript == null))
                {
                    if (GUILayout.Button("Set Default", GUILayout.Width(90)))
                    {
                        string templateError;
                        string templatePath = AssetDatabase.GetAssetPath(exampleScript);
                        if (AdvancedUIToolkitCodeTemplate.Validate(templatePath, out templateError))
                            AdvancedUIToolkitCodeTemplate.SetDefaultTemplate(exampleScript);
                        else
                            EditorUtility.DisplayDialog("Invalid generation template", templateError, "OK");
                    }
                }
            }
            if (AdvancedUIToolkitCodeTemplate.GetDefaultTemplate() != null &&
                GUILayout.Button("Clear Global Default Template"))
                AdvancedUIToolkitCodeTemplate.SetDefaultTemplate(null);
            EditorGUILayout.HelpBox(
                "Optional: select an ExampleScript.cs template using the ADVANCEDUITOOLKIT:PROPERTIES and " +
                "ADVANCEDUITOOLKIT:ASSIGNMENTS markers. The generator preserves its layout and comments. " +
                "Changes to a template require manual regeneration.", MessageType.None);

            // Validate options before allowing writes.
            if (GUILayout.Button("Validate Preview")) Validate();
            using (new EditorGUI.DisabledScope(
                target == null || scanFingerprint == null || errors.Count != 0 ||
                (candidates.Count == 0 && removed.Count == 0)))
            {
                if (GUILayout.Button(new GUIContent("Preview Generated C#",
                    "Inspect the proposed source and changes without writing files or triggering compilation.")))
                    PreviewGeneratedSource();
                if (GUILayout.Button("Save Manifest + Generate C#")) Generate();
            }
        }

        /// <summary>
        /// Read-only information about one discovered UI component for the simplified workspace.
        /// </summary>
        internal sealed class WorkspaceBinding
        {
            /// <summary>The named Unity component.</summary>
            internal Component Component;
            /// <summary>The name used to create the generated property.</summary>
            internal string ApiKey;
            /// <summary>The key inferred from the GameObject name.</summary>
            internal string HierarchyKey;
            /// <summary>The type of component discovered by naming conventions.</summary>
            internal string ComponentType;
            /// <summary>The optional, user-authored XML summary.</summary>
            internal string XmlSummary;
            /// <summary>The human-readable change classification.</summary>
            internal string Change;
            /// <summary>Whether the generated accessor is new or has been renamed.</summary>
            internal bool RequiresGeneration;
        }

        /// <summary>Gets the selected UI root without exposing the scanner's mutable state.</summary>
        internal GameObject WorkspaceTarget => target;

        /// <summary>Gets the current number of binding validation errors.</summary>
        internal int WorkspaceErrorCount => errors.Count;

        /// <summary>Gets the current number of warnings, including breaking changes.</summary>
        internal int WorkspaceWarningCount => warnings.Count;

        /// <summary>Gets the number of previously registered components that no longer exist.</summary>
        internal int WorkspaceRemovedCount => removed.Count;

        /// <summary>True when the current hierarchy has been scanned.</summary>
        internal bool WorkspaceHasScan => scanFingerprint != null;

        /// <summary>True when the generated class and manifest can be written.</summary>
        internal bool WorkspaceCanGenerate => target != null && scanFingerprint != null &&
            errors.Count == 0 && (candidates.Count > 0 || removed.Count > 0);

        /// <summary>
        /// Determines whether the class name, namespace, folder, or example script differs
        /// from the settings saved with the current binding manifest.
        /// </summary>
        internal bool WorkspaceHasConfigurationChanges
        {
            get
            {
                if (target == null) return false;
                UIBindingRoot root = target.GetComponent<UIBindingRoot>();
                if (root == null || !root.EditorHasGenerationProfile) return true;
                root.EditorGetGenerationProfile(out string savedClass, out string savedNamespace,
                    out string savedFolder);
                string examplePath = exampleScript != null
                    ? AssetDatabase.GetAssetPath(exampleScript) : string.Empty;
                return !string.Equals(savedClass, className, StringComparison.Ordinal) ||
                    !string.Equals(savedNamespace, namespaceName, StringComparison.Ordinal) ||
                    !string.Equals(savedFolder, outputFolder, StringComparison.Ordinal) ||
                    !string.Equals(root.EditorGetGenerationTemplatePath() ?? string.Empty,
                        examplePath ?? string.Empty, StringComparison.Ordinal);
            }
        }

        /// <summary>Gets the number of newly created or renamed public accessors.</summary>
        internal int WorkspaceChangeCount => candidates.Count(candidate =>
            string.IsNullOrEmpty(candidate.PreviousKey) ||
            !string.Equals(candidate.PreviousKey, candidate.ApiKey, StringComparison.Ordinal) ||
            !string.Equals(candidate.PreviousHierarchyKey, candidate.HierarchyKey,
                StringComparison.Ordinal) ||
            !string.Equals(candidate.PreviousXmlSummary ?? string.Empty,
                candidate.XmlSummary ?? string.Empty, StringComparison.Ordinal)) + removed.Count;

        /// <summary>Returns the current binding list for display without allowing modifications.</summary>
        internal List<WorkspaceBinding> GetWorkspaceBindings()
        {
            if (workspaceBindingSnapshot != null) return workspaceBindingSnapshot;
            List<WorkspaceBinding> snapshot = new List<WorkspaceBinding>(candidates.Count);
            foreach (BindingCandidate candidate in candidates)
            {
                snapshot.Add(new WorkspaceBinding
                {
                    Component = candidate.Reference,
                    ApiKey = candidate.ApiKey,
                    HierarchyKey = candidate.HierarchyKey,
                    ComponentType = candidate.ComponentType,
                    XmlSummary = candidate.XmlSummary,
                    Change = Describe(candidate),
                    RequiresGeneration = string.IsNullOrEmpty(candidate.PreviousKey) ||
                        !string.Equals(candidate.PreviousKey, candidate.ApiKey, StringComparison.Ordinal) ||
                        !string.Equals(candidate.PreviousHierarchyKey, candidate.HierarchyKey,
                            StringComparison.Ordinal) ||
                        !string.Equals(candidate.PreviousXmlSummary ?? string.Empty,
                            candidate.XmlSummary ?? string.Empty, StringComparison.Ordinal)
                });
            }
            workspaceBindingSnapshot = snapshot;
            return snapshot;
        }

        /// <summary>Gets current error and warning text for a compact inline summary.</summary>
        internal List<string> GetWorkspaceIssues(bool includeWarnings)
        {
            List<string> issues = new List<string>(errors);
            if (includeWarnings) issues.AddRange(warnings);
            return issues;
        }

