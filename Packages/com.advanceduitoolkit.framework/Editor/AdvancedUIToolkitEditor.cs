        /// <summary>
        /// Draws the per-binding XML summary directly above its generated public property.
        /// Empty summaries retain the template default. Editing changes only the staged
        /// preview until the developer generates; no C# files are written on each keystroke.
        /// </summary>
        internal void DrawWorkspacePropertyDocumentation(string search = null)
        {
            if (candidates.Count == 0) return;
            EditorGUILayout.LabelField("Public property names and XML comments", EditorStyles.boldLabel);
            EditorGUILayout.LabelField(
                "Leave XML Summary empty to use the default. Generate to save changes.",
                EditorStyles.wordWrappedMiniLabel);
            int shown = 0;
            foreach (BindingCandidate candidate in candidates)
            {
                if (candidate.Reference == null || !MatchesBindingSearch(search,
                    candidate.Reference.gameObject.name, candidate.ApiKey, candidate.HierarchyKey))
                    continue;
                shown++;
                using (new EditorGUILayout.VerticalScope(EditorStyles.helpBox))
                {
                    EditorGUILayout.LabelField(candidate.HierarchyKey, EditorStyles.miniBoldLabel);
                    string nextSummary = EditorGUILayout.TextField(
                        new GUIContent("XML Summary", "Text placed inside the generated property's <summary> tag."),
                        candidate.XmlSummary ?? string.Empty);
                    string nextKey = EditorGUILayout.TextField("Public Property", candidate.ApiKey);
                    if (!string.Equals(nextSummary, candidate.XmlSummary, StringComparison.Ordinal) ||
                        !string.Equals(nextKey, candidate.ApiKey, StringComparison.Ordinal))
                        UpdateWorkspaceProperty(candidate.Reference, nextSummary, nextKey);
                }
            }
            if (shown == 0)
                GUILayout.Label("No matching properties. Clear the component search to see all fields.",
                    EditorStyles.wordWrappedMiniLabel);
        }

        /// <summary>
        /// Uses one filtering rule for the component list and the XML documentation editor.
        /// Searches object names, generated property names and hierarchy-derived keys.
        /// </summary>
        /// <param name="query">Optional search term.</param>
        /// <param name="objectName">Name in Unity's Hierarchy.</param>
        /// <param name="propertyName">Generated public accessor name.</param>
        /// <param name="hierarchyKey">Hierarchy-derived accessor key.</param>
        /// <returns>True if the component should be displayed.</returns>
        internal static bool MatchesBindingSearch(string query, string objectName,
            string propertyName, string hierarchyKey)
        {
            if (string.IsNullOrWhiteSpace(query)) return true;
            string term = query.Trim();
            return (!string.IsNullOrEmpty(objectName) &&
                    objectName.IndexOf(term, StringComparison.OrdinalIgnoreCase) >= 0) ||
                   (!string.IsNullOrEmpty(propertyName) &&
                    propertyName.IndexOf(term, StringComparison.OrdinalIgnoreCase) >= 0) ||
                   (!string.IsNullOrEmpty(hierarchyKey) &&
                    hierarchyKey.IndexOf(term, StringComparison.OrdinalIgnoreCase) >= 0);
        }

        /// <summary>
        /// Stages a property name and XML summary edit on the discovered component.
        /// Matching by Component rather than array index preserves identity across renames.
        /// </summary>
        /// <param name="component">The discovered Unity component to edit.</param>
        /// <param name="xmlSummary">Literal description to place in its XML summary.</param>
        /// <param name="apiKey">Public property name to generate.</param>
        /// <returns>True when a binding's staged metadata changed.</returns>
        internal bool UpdateWorkspaceProperty(Component component, string xmlSummary, string apiKey)
        {
            BindingCandidate candidate = candidates.FirstOrDefault(c => c.Reference == component);
            if (candidate == null) return false;
            string nextSummary = xmlSummary ?? string.Empty;
            if (string.Equals(candidate.XmlSummary ?? string.Empty, nextSummary, StringComparison.Ordinal) &&
                string.Equals(candidate.ApiKey, apiKey, StringComparison.Ordinal))
                return false;
            candidate.XmlSummary = nextSummary;
            candidate.ApiKey = apiKey;
            workspaceBindingSnapshot = null;
            hasUnsavedBindingEdits = candidates.Any(HasStagedPropertyEdit);
            Validate();
            return true;
        }

        /// <summary>Loads a selected UI root and scans its current named controls.</summary>
        /// <param name="selected">The screen or panel to inspect.</param>
        internal void SetWorkspaceTarget(GameObject selected)
        {
            SetTarget(selected);
            Scan();
        }

        /// <summary>Performs the describe operation.</summary>
        private static string Describe(BindingCandidate candidate)
        {
            if (string.IsNullOrEmpty(candidate.PreviousKey)) return "New binding";
            if (!string.Equals(candidate.PreviousKey, candidate.ApiKey, StringComparison.Ordinal))
                return $"BREAKING API RENAME: {candidate.PreviousKey} -> {candidate.ApiKey}";
            if (!string.Equals(candidate.HierarchyKey, candidate.PreviousHierarchyKey,
                StringComparison.Ordinal))
                return "GameObject renamed; generated API is preserved";
            if (!string.Equals(candidate.PreviousXmlSummary ?? string.Empty,
                candidate.XmlSummary ?? string.Empty, StringComparison.Ordinal))
                return "XML summary changed";
            return "Unchanged";
        }

        /// <summary>Suggests a readable binding class name for a newly authored UI root.</summary>
        /// <param name="objectName">The root GameObject name.</param>
        /// <returns>A valid candidate class name ending in Bindings.</returns>
        internal static string SuggestClassName(string objectName)
        {
            if (string.IsNullOrWhiteSpace(objectName)) return "ScreenBindings";
            int underscore = objectName.IndexOf('_');
            if (underscore > 0 && Types.ContainsKey(objectName.Substring(0, underscore)))
                objectName = objectName.Substring(underscore + 1);
            string identifier = new string(objectName.Where(char.IsLetterOrDigit).ToArray());
            if (string.IsNullOrEmpty(identifier)) return "ScreenBindings";
            if (char.IsDigit(identifier[0])) identifier = "_" + identifier;
            return identifier.EndsWith("Bindings", StringComparison.Ordinal)
                ? identifier : identifier + "Bindings";
        }

        /// <summary>Loads the target's generation settings or uses clean defaults for new roots.</summary>
        /// <param name="selected">The GameObject to inspect.</param>
        private void SetTarget(GameObject selected)
        {
            target = selected;
            ClearScan();
            className = SuggestClassName(target != null ? target.name : null);
            namespaceName = "Game.UI.Generated";
            outputFolder = "Assets/AdvancedUIToolkit/Generated";
            exampleScript = AdvancedUIToolkitCodeTemplate.GetDefaultTemplate();
            if (target == null) return;
            UIBindingRoot root = target.GetComponent<UIBindingRoot>();
            if (root == null || !root.EditorHasGenerationProfile) return;
            root.EditorGetGenerationProfile(out className, out namespaceName, out outputFolder);
            string templatePath = root.EditorGetGenerationTemplatePath();
            exampleScript = string.IsNullOrEmpty(templatePath)
                ? null : AssetDatabase.LoadAssetAtPath<MonoScript>(templatePath);
        }

        /// <summary>Performs the clear scan operation.</summary>
        private void ClearScan()
        {
            workspaceBindingSnapshot = null;
            candidates.Clear();
            removed.Clear();
            errors.Clear();
            warnings.Clear();
            scanFingerprint = null;
            hasUnsavedBindingEdits = false;
        }

        /// <summary>
        /// Rebuilds the discovered binding list. Hierarchy-triggered scans may preserve
        /// pending per-property edits, matching by Unity Component identity instead of
        /// list order or a name that may have changed during duplication.
        /// </summary>
        /// <param name="preserveStagedEdits">Whether to keep ungenerated XML summaries and public names.</param>
        /// <param name="normalizeUnityDuplicates">Whether the interactive Binder may correct Unity's duplicate suffixes.</param>
        private void Scan(bool preserveStagedEdits = false, bool normalizeUnityDuplicates = true)
        {
            Dictionary<Component, BindingCandidate> staged = null;
            if (preserveStagedEdits && hasUnsavedBindingEdits)
                staged = candidates.Where(c => c.Reference != null)
                    .GroupBy(c => c.Reference)
                    .ToDictionary(group => group.Key, group => group.First());

            ClearScan();
            if (target == null) { errors.Add("Select a UI root."); return; }
            string targetError = UIBindingSafety.GetTargetError(target);
            if (targetError != null)
            {
                errors.Add(targetError);
                return;
            }

            // Unity's Ctrl+D names clones "BTN_Load (1)", which is not a valid C#
            // identifier. Normalize only this recognizable Unity-generated suffix;
            // intentionally duplicated names and unrelated names still get the
            // usual validation errors. This is a derived naming fix, not an extra
            // Undo operation that could interfere with Ctrl+Z of the duplication.
            if (normalizeUnityDuplicates) NormalizeUnityDuplicateNames();

            UIBindingRoot bindingRoot = target.GetComponent<UIBindingRoot>();
            List<UIBindingRoot.Entry> previous = bindingRoot != null
                ? bindingRoot.EditorGetEntries().Where(e => e != null).ToList()
                : new List<UIBindingRoot.Entry>();

            // Unity's Component object identity survives GameObject rename and reparenting.
            // When upgrading from v0.3, retain the existing public Key and assign a GUID.
            Dictionary<Component, UIBindingRoot.Entry> byComponent = new Dictionary<Component, UIBindingRoot.Entry>();
            foreach (UIBindingRoot.Entry entry in previous)
            {
                if (entry.Reference != null && !byComponent.ContainsKey(entry.Reference))
                    byComponent.Add(entry.Reference, entry);
            }

            HashSet<UIBindingRoot.Entry> seenPrevious = new HashSet<UIBindingRoot.Entry>();
            foreach (FoundComponent item in FindBindableComponents())
            {
                UIBindingRoot.Entry old;
                byComponent.TryGetValue(item.Reference, out old);
                if (old != null) seenPrevious.Add(old);

                string oldKey = old != null ? old.Key : null;
                BindingCandidate candidate = new BindingCandidate
                {
                    Reference = item.Reference,
                    ComponentType = item.ComponentType,
                    HierarchyKey = item.Key,
                    PreviousKey = oldKey,
                    PreviousHierarchyKey = old != null ? old.HierarchyKey : null,
                    ApiKey = preserveExistingApi && !string.IsNullOrEmpty(oldKey) ? oldKey : item.Key,
                    XmlSummary = old != null ? old.XmlSummary ?? string.Empty : string.Empty,
                    PreviousXmlSummary = old != null ? old.XmlSummary ?? string.Empty : string.Empty,
                    StableId = old != null && !string.IsNullOrEmpty(old.StableId)
                        ? old.StableId : Guid.NewGuid().ToString("N")
                };
                if (staged != null && staged.TryGetValue(item.Reference, out BindingCandidate edit))
                {
                    candidate.ApiKey = edit.ApiKey;
                    candidate.XmlSummary = edit.XmlSummary;
                }
                candidates.Add(candidate);
            }

            foreach (UIBindingRoot.Entry entry in previous)
                if (!seenPrevious.Contains(entry)) removed.Add(entry);

            candidates.Sort((a, b) => string.CompareOrdinal(a.HierarchyKey, b.HierarchyKey));
            hasUnsavedBindingEdits = candidates.Any(HasStagedPropertyEdit);
            scanFingerprint = GetFingerprint();
            Validate();
        }

        /// <summary>
        /// A property is staged when its public name or XML summary differs from the
        /// saved manifest. Newly found controls start with default metadata and do not
        /// need to be treated as manually edited for rescan preservation.
        /// </summary>
        /// <param name="candidate">The current scan candidate.</param>
        /// <returns>True when a property has unpublished user-authored metadata.</returns>
        private static bool HasStagedPropertyEdit(BindingCandidate candidate) =>
            string.IsNullOrEmpty(candidate.PreviousKey)
                ? !string.Equals(candidate.HierarchyKey, candidate.ApiKey, StringComparison.Ordinal) ||
                  !string.IsNullOrEmpty(candidate.XmlSummary)
                : !string.Equals(candidate.PreviousKey, candidate.ApiKey, StringComparison.Ordinal) ||
                  !string.Equals(candidate.PreviousXmlSummary ?? string.Empty,
                      candidate.XmlSummary ?? string.Empty, StringComparison.Ordinal);

        /// <summary>
        /// Repairs Unity's default numbered duplication suffix for recognizable named
        /// controls, so Ctrl+D results in BTN_Fire_2 rather than BTN_Fire (1).
        /// Other names are never silently changed. Names remain unique across the
        /// current binding scope, even when duplicates are in different containers.
        /// </summary>
        private void NormalizeUnityDuplicateNames()
        {
            List<Transform> transforms = target.GetComponentsInChildren<Transform>(true)
                .Where(t => !BelongsToNestedRoot(t, target.transform)).ToList();
            HashSet<string> names = new HashSet<string>(transforms.Select(t => t.name), StringComparer.Ordinal);
            foreach (Transform transform in transforms)
            {
                if (!TryGetUnityDuplicateBase(transform.name, out string baseName,
                    out int proposedSuffix)) continue;

                string proposedName;
                do
                {
                    proposedName = baseName + "_" + proposedSuffix;
                    proposedSuffix++;
                }
                while (names.Contains(proposedName));

                names.Remove(transform.name);
                transform.name = proposedName;
                names.Add(proposedName);
                if (PrefabUtility.IsPartOfPrefabInstance(transform.gameObject))
                    PrefabUtility.RecordPrefabInstancePropertyModifications(transform.gameObject);
            }
        }

        /// <summary>
        /// Recognizes Unity's Ctrl+D suffix without rewriting arbitrary user names.
        /// </summary>
        /// <param name="name">The actual Unity GameObject name.</param>
        /// <param name="baseName">The valid prefix/name without the duplicate suffix.</param>
        /// <param name="suffix">The proposed unique-name suffix.</param>
        /// <returns>True if this is a recognized Unity-generated duplicate name.</returns>
        private static bool TryGetUnityDuplicateBase(string name, out string baseName,
            out int suffix)
        {
            baseName = null;
            suffix = 0;
            if (string.IsNullOrEmpty(name) || !name.EndsWith(")", StringComparison.Ordinal))
                return false;
            int opening = name.LastIndexOf(" (", StringComparison.Ordinal);
            if (opening < 0 || !int.TryParse(name.Substring(opening + 2,
                name.Length - opening - 3), out int duplicateIndex) || duplicateIndex < 1 ||
                duplicateIndex == int.MaxValue)
                return false;

            string candidate = name.Substring(0, opening);
            int separator = candidate.IndexOf('_');
            if (separator < 1 || separator == candidate.Length - 1 ||
                !Types.ContainsKey(candidate.Substring(0, separator)) ||
                !IsLegalIdentifier(candidate.Substring(separator + 1)))
                return false;
            baseName = candidate;
            suffix = duplicateIndex + 1;
            return true;
        }

        /// <summary>Defines the found component struct.</summary>
        private struct FoundComponent
        {
            /// <summary>Stores the key reference or configuration value.</summary>
            public string Key;
            /// <summary>Stores the component type reference or configuration value.</summary>
            public string ComponentType;
            /// <summary>Stores the reference reference or configuration value.</summary>
            public Component Reference;
        }

        /// <summary>Finds bindable components.</summary>
        private IEnumerable<FoundComponent> FindBindableComponents()
        {
            if (target == null) yield break;
            foreach (Transform transform in target.GetComponentsInChildren<Transform>(true))
            {
                if (BelongsToNestedRoot(transform, target.transform)) continue;
                string goName = transform.name;
                int index = goName.IndexOf('_');
                if (index <= 0) continue;
                string prefix = goName.Substring(0, index);
                Type type;
                if (!Types.TryGetValue(prefix, out type)) continue;
                Component component = AdvancedUIToolkitNaming.ResolveNamedComponent(
                    transform, type, out _);
                if (component == null)
                {
                    // Validation reports absent or ambiguous child components.
                    continue;
                }
                yield return new FoundComponent
                {
                    Key = goName.Substring(index + 1),
                    ComponentType = type.FullName,
                    Reference = component
                };
            }
        }

        /// <summary>Performs the belongs to nested root operation.</summary>
        private static bool BelongsToNestedRoot(Transform current, Transform selectedRoot)
        {
            for (Transform ancestor = current; ancestor != null && ancestor != selectedRoot; ancestor = ancestor.parent)
            {
                if (ancestor.GetComponent<UIBindingRoot>() != null)
                    return true;
            }
            return false;
        }

        /// <summary>Gets fingerprint.</summary>
        private string GetFingerprint()
        {
            if (target == null) return "";
            List<string> parts = new List<string>();
            foreach (Transform transform in target.GetComponentsInChildren<Transform>(true))
            {
                if (BelongsToNestedRoot(transform, target.transform)) continue;
                int index = transform.name.IndexOf('_');
                if (index <= 0) continue;
                Type type;
                if (!Types.TryGetValue(transform.name.Substring(0, index), out type)) continue;
                Component component = AdvancedUIToolkitNaming.ResolveNamedComponent(
                    transform, type, out string resolutionProblem);
                parts.Add(transform.GetInstanceID() + ":" + transform.name + ":" +
                    (component != null ? component.GetInstanceID().ToString() :
                        resolutionProblem ?? "missing"));
            }
            parts.Sort(StringComparer.Ordinal);
            return AdvancedUIToolkitNaming.RegistrationVersion + "|" + string.Join("|", parts.ToArray());
        }

        /// <summary>Validates value.</summary>
        private void Validate()
        {
            errors.Clear();
            warnings.Clear();
            if (target == null) { errors.Add("Select a UI root."); return; }
            string targetError = UIBindingSafety.GetTargetError(target);
            if (targetError != null) errors.Add(targetError);
            if (scanFingerprint == null)
            {
                errors.Add("Scan your UI root first.");
                return;
            }

            HashSet<string> seenApi = new HashSet<string>(StringComparer.Ordinal);
            HashSet<string> seenHierarchy = new HashSet<string>(StringComparer.Ordinal);
            HashSet<string> seenIds = new HashSet<string>(StringComparer.Ordinal);
            HashSet<Component> seenReferences = new HashSet<Component>();
            foreach (BindingCandidate candidate in candidates)
            {
                if (!IsLegalIdentifier(candidate.HierarchyKey))
                    errors.Add("Invalid hierarchy key: " + candidate.HierarchyKey);
                if (!seenHierarchy.Add(candidate.HierarchyKey))
                    errors.Add("Duplicate hierarchy key: " + candidate.HierarchyKey);
                if (!IsLegalIdentifier(candidate.ApiKey))
                    errors.Add("Invalid generated API key: " + candidate.ApiKey);
                if (!seenApi.Add(candidate.ApiKey))
                    errors.Add("Duplicate generated API key: " + candidate.ApiKey);
                if (!seenIds.Add(candidate.StableId))
                    errors.Add("Duplicate stable binding ID: " + candidate.StableId);
                if (candidate.Reference == null)
                    errors.Add("Missing component for: " + candidate.HierarchyKey);
                else
                {
                    if (!seenReferences.Add(candidate.Reference))
                        errors.Add("Multiple binding names resolve to the same component: " +
                            candidate.HierarchyKey + ". Use one name for that component.");
                    UIBindingRoot owner = target.GetComponent<UIBindingRoot>();
                    if (owner != null && !UIBindingSafety.IsInScope(owner, candidate.Reference))
                        errors.Add("Binding '" + candidate.ApiKey +
                                   "' references a component owned by a different UI root.");
                }
                if (!string.IsNullOrEmpty(candidate.PreviousKey) && candidate.ApiKey != candidate.PreviousKey)
                    warnings.Add($"API rename: {candidate.PreviousKey} -> {candidate.ApiKey}. " +
                        "Update any scripts that use the old generated property.");
            }

            // Identify prefix-matching GameObjects missing the correct Component.
            foreach (Transform transform in target.GetComponentsInChildren<Transform>(true))
            {
                if (BelongsToNestedRoot(transform, target.transform)) continue;
                int index = transform.name.IndexOf('_');
                if (index <= 0) continue;
                Type type;
                if (!Types.TryGetValue(transform.name.Substring(0, index), out type)) continue;
                if (AdvancedUIToolkitNaming.ResolveNamedComponent(transform, type,
                    out string resolutionProblem) == null)
                    errors.Add(transform.name + " " + resolutionProblem);
            }

            if (!IsLegalIdentifier(className)) errors.Add("Invalid generated class name: " + className);
            if (candidates.Any(c => c.ApiKey == className))
                errors.Add("A generated property cannot have the same name as its containing class.");
            if (string.IsNullOrEmpty(namespaceName) ||
                namespaceName.Split('.').Any(part => !IsLegalIdentifier(part)))
                errors.Add("Invalid namespace: " + namespaceName);

            string folder = outputFolder.Replace('\\', '/');
            if (!folder.StartsWith("Assets/", StringComparison.Ordinal) ||
                folder.Contains("..") || folder.Contains(":") || folder.Contains("//"))
                errors.Add("Output folder must be a safe relative folder under Assets/.");

            if (exampleScript != null)
            {
                string templatePath = AssetDatabase.GetAssetPath(exampleScript);
                string templateError;
                if (!AdvancedUIToolkitCodeTemplate.Validate(templatePath, out templateError))
                    errors.Add("Invalid ExampleScript.cs template: " + templateError);
            }

            // Keep existing broken entries visible even when the next generation can
            // deliberately repair them by rebuilding the manifest from the hierarchy.
            UIBindingRoot savedRoot = target.GetComponent<UIBindingRoot>();
            if (savedRoot != null && savedRoot.EditorGetEntries().Count > 0)
                UIBindingSafety.ValidateManifest(savedRoot, savedRoot.EditorGetEntries(),
                    issue => warnings.Add("Saved manifest: " + issue +
                                          " A reviewed regeneration can repair this entry."));
            UIBindingSafety.AppendNestedPrefabWarnings(target, warnings);
            if (removed.Count > 0)
                warnings.Add($"{removed.Count} previously generated accessor(s) will be removed. " +
                             "Existing code may need updating.");
            // An existing root may legitimately have zero controls after the last
            // bound prefab instance is deleted. Generate an empty class/manifest
            // rather than keeping stale accessors. A new empty root still needs
            // at least one bindable control before its first generation.
            if (candidates.Count == 0 && removed.Count == 0)
                errors.Add("No bindable UI elements found.");
        }

        /// <summary>Determines whether legal identifier.</summary>
        private static bool IsLegalIdentifier(string name)
        {
            if (string.IsNullOrEmpty(name) ||
                !(char.IsLetter(name[0]) || name[0] == '_') ||
                AdvancedUIToolkitNaming.IsReservedAccessorName(name)) return false;
            return name.All(ch => char.IsLetterOrDigit(ch) || ch == '_');
        }

        /// <summary>
        /// Inspection and optional safe regeneration used by Advanced UI Toolkit Automation.
        /// Does not modify a scene, prefab, or script when apply == false.
        /// The v0.5 roots need one manual generation to save their output profile.
        /// </summary>
        internal static UIAutoGenerationResult InspectForAutomation(UIBindingRoot root, bool apply)
        {
            if (root == null)
                return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked, "Missing UI binding root.");
            if (EditorUtility.IsPersistent(root))
                return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                    "Prefab asset: open in Prefab Mode for automatic processing.");
            if (PrefabUtility.IsPartOfPrefabInstance(root))
                return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                    "Prefab instance overrides are not auto-generated. Open the source prefab " +
                    "in Prefab Mode, or review this instance manually in AutoBinder.");
            if (!root.EditorHasGenerationProfile)
                return new UIAutoGenerationResult(UIAutoGenerationStatus.SetupRequired,
                    "Open AutoBinder and generate once to register the class and output path.");

            UIAutoBinderWindow instance = CreateInstance<UIAutoBinderWindow>();
            try
            {
                instance.target = root.gameObject;
                root.EditorGetGenerationProfile(out instance.className,
                    out instance.namespaceName, out instance.outputFolder);
                string savedTemplate = root.EditorGetGenerationTemplatePath();
                instance.exampleScript = string.IsNullOrEmpty(savedTemplate)
                    ? null : AssetDatabase.LoadAssetAtPath<MonoScript>(savedTemplate);
                if (!string.IsNullOrEmpty(savedTemplate) && instance.exampleScript == null)
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                        "Generation template is missing. Open the Bindings tab to choose a template.");
                instance.preserveExistingApi = true;
                // An inspection (apply=false) must never rename scene objects.
                // Background automation only reads the current hierarchy; the
                // interactive Binder is responsible for Ctrl+D name repair.
                instance.Scan(false, false);
                if (instance.errors.Count != 0)
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                        string.Join("; ", instance.errors.ToArray()));
                if (instance.candidates.Any(c => !string.IsNullOrEmpty(c.PreviousKey) &&
                    !string.Equals(c.PreviousKey, c.ApiKey, StringComparison.Ordinal)))
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                        "Public accessor rename detected. Manual approval is required.");

                string path = instance.outputFolder.Replace('\\', '/') + "/" +
                    instance.className + ".cs";
                if (!File.Exists(path))
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                        "Generated source not found at " + path + ". Open AutoBinder to regenerate.");

                // Only automatically rewrite files that still match the source generated
                // from the OLD saved manifest. Protects developer edits or path collisions.
                List<UIBindingRoot.Entry> oldEntries = root.EditorGetEntries().Where(e => e != null).ToList();
                string expectedOldSource = instance.BuildGeneratedSource(oldEntries);
                if (!string.Equals(File.ReadAllText(path), expectedOldSource, StringComparison.Ordinal))
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                        "Generated file differs from the saved manifest (edited or shared path). " +
                        "Review in AutoBinder before overwriting.");

                bool changed = instance.candidates.Count != oldEntries.Count ||
                    instance.candidates.Any(c => !oldEntries.Any(e =>
                        e.Reference == c.Reference &&
                        e.Key == c.ApiKey &&
                        e.HierarchyKey == c.HierarchyKey &&
                        e.ComponentType == c.ComponentType &&
                        e.StableId == c.StableId &&
                        string.Equals(e.XmlSummary ?? string.Empty,
                            c.XmlSummary ?? string.Empty, StringComparison.Ordinal)));
                if (!changed)
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.UpToDate,
                        "Manifest and hierarchy are synchronized.");
                if (!apply)
                {
                    if (instance.removed.Count > 0)
                        return new UIAutoGenerationResult(UIAutoGenerationStatus.PendingRemoval,
                            instance.removed.Count + " deleted binding(s) awaiting regeneration. " +
                            "The corresponding C# accessors will be removed. " +
                            "Scripts using them must be updated.");
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.SafeChange,
                        "Safe additions or hierarchy renames detected; public API names preserved.");
                }
                // Automation only reaches this point after validating the old generated
                // source against the saved manifest. Explicitly authorize removals;
                // never bypass the separate ownership, path or source-edit checks.
                if (!instance.Generate(false, instance.removed.Count > 0))
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                        string.Join("; ", instance.errors.ToArray()));
                return new UIAutoGenerationResult(UIAutoGenerationStatus.Generated,
                    "Updated manifest and generated accessors. Save the scene or prefab. " +
                    "Update scripts that used any removed properties.");
            }
            catch (Exception ex)
            {
                return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                    ex.GetType().Name + ": " + ex.Message);
            }
            finally
            {
                DestroyImmediate(instance);
            }
        }

        /// <summary>
        /// Performs the initial noninteractive generation for an unregistered UI hierarchy.
        /// Reuses Binder's normal scan, safety checks and recoverable source commit, but
        /// never opens an Editor window or edits hierarchy names during discovery.
        /// </summary>
        /// <param name="setup">Fully specified class name, namespace, path and optional template.</param>
        /// <returns>A status and message from Binder's existing generation pipeline.</returns>
        internal static UIAutoGenerationResult InitializeForIntegration(UIEditorBindingSetup setup)
        {
            if (setup == null || setup.Target == null)
                return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                    "An editable target GameObject is required.");
            UIBindingRoot existingRoot = setup.Target.GetComponent<UIBindingRoot>();
            if (existingRoot != null && existingRoot.EditorHasGenerationProfile)
                return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                    "This UI root already has a generation profile. Use GenerateBindings instead.");

            UIAutoBinderWindow instance = CreateInstance<UIAutoBinderWindow>();
            try
            {
                instance.SetTarget(setup.Target);
                instance.className = setup.ClassName;
                instance.namespaceName = setup.NamespaceName;
                instance.outputFolder = setup.OutputFolder;
                // A null template explicitly selects the standard built-in generator.
                instance.exampleScript = setup.TemplateScript;
                instance.preserveExistingApi = true;
                instance.Scan(false, false);
                if (instance.errors.Count != 0)
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                        string.Join("; ", instance.errors.ToArray()));
                if (!instance.Generate(false))
                    return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                        string.Join("; ", instance.errors.ToArray()));
                return new UIAutoGenerationResult(UIAutoGenerationStatus.Generated,
                    "Created a binding manifest and generated C# source. Save the scene or prefab.");
            }
            catch (Exception exception)
            {
                return new UIAutoGenerationResult(UIAutoGenerationStatus.Blocked,
                    exception.GetType().Name + ": " + exception.Message);
            }
            finally
            {
                DestroyImmediate(instance);
            }
        }

        /// <summary>Opens a read-only preview without modifying files, manifests, or assets.</summary>
        private void PreviewGeneratedSource()
        {
            Validate();
            if (errors.Count != 0 || (candidates.Count == 0 && removed.Count == 0) || target == null)
                return;
            if (scanFingerprint == null ||
                !string.Equals(scanFingerprint, GetFingerprint(), StringComparison.Ordinal))
            {
                errors.Add("Hierarchy changed since the last scan. Scan again to preview.");
                return;
            }

            string folder = outputFolder.Replace('\\', '/').TrimEnd('/');
            if (!IsSafeOutputFolder(folder))
            {
                errors.Add("Output must be inside the project's Assets directory.");
                return;
            }
            List<UIBindingRoot.Entry> manifest = candidates.OrderBy(candidate => candidate.ApiKey, StringComparer.Ordinal)
                .Select(candidate => new UIBindingRoot.Entry
                {
                    Key = candidate.ApiKey,
                    HierarchyKey = candidate.HierarchyKey,
                    ComponentType = candidate.ComponentType,
                    StableId = candidate.StableId,
                    XmlSummary = candidate.XmlSummary,
                    Reference = candidate.Reference
                }).ToList();
            try
            {
                string destination = folder + "/" + className + ".cs";
                string proposed = BuildGeneratedSource(manifest);
                string current = File.Exists(destination) ? File.ReadAllText(destination) : null;
                AdvancedUIToolkitGenerationPreviewWindow.Open(destination, proposed, current);
            }
            catch (Exception exception)
            {
                errors.Add("Cannot build a generation preview: " + exception.Message);
            }
        }

        /// <summary>Generates value.</summary>
        private void Generate() => Generate(true);

        /// <summary>Generates value.</summary>
        /// <summary>
        /// Writes a reviewed or automation-validated manifest and generated class.
        /// The automation path may remove properties only when it verified the
        /// previous generated source has not been modified externally.
        /// </summary>
        /// <param name="interactive">Whether to ask before breaking public API changes.</param>
        /// <param name="allowRemovedAccessors">Whether a validated automatic update may remove accessors.</param>
        /// <returns>True when source and manifest were updated successfully.</returns>
        private bool Generate(bool interactive, bool allowRemovedAccessors = false)
        {
            Validate();
            if (errors.Count > 0) return false;
            if (!string.Equals(scanFingerprint, GetFingerprint(), StringComparison.Ordinal))
            {
                errors.Add("UI hierarchy changed since the last scan. Scan again before generating.");
                return false;
            }

            string folder = outputFolder.Replace('\\', '/').TrimEnd('/');
            // Generated code belongs to the consuming project's Assets folder,
            // never inside a read-only UPM package or outside the project.
            if (!IsSafeOutputFolder(folder))
            {
                errors.Add("Output folder must be inside this project's Assets folder " +
                    "(e.g. Assets/AdvancedUIToolkit/Generated). Package directories and '..' are not allowed.");
                return false;
            }
            string path = folder + "/" + className + ".cs";
            UIBindingRoot existingRoot = target.GetComponent<UIBindingRoot>();
            if (existingRoot != null && existingRoot.EditorHasGenerationProfile)
            {
                existingRoot.EditorGetGenerationProfile(out string oldClass,
                    out string oldNamespace, out string oldFolder);
                string oldPath = oldFolder.Replace('\\', '/').TrimEnd('/') + "/" + oldClass + ".cs";
                if (!string.Equals(oldPath, path, StringComparison.OrdinalIgnoreCase) &&
                    File.Exists(oldPath))
                {
                    errors.Add("This UI root previously generated '" + oldPath + "'. " +
                               "Move or delete that old generated file deliberately before switching " +
                               "class name or output path, to avoid duplicate C# definitions.");
                    return false;
                }
            }
            string ownershipError = UIBindingSafety.GetExistingFileError(existingRoot, path);
            if (ownershipError == null)
                ownershipError = UIBindingSafety.GetOtherOwnerError(target, path);
            if (ownershipError != null)
            {
                errors.Add(ownershipError);
                return false;
            }
            // Keep one validated snapshot for the entire generation transaction.
            // The commit helper refuses to overwrite if the file changes afterward.
            string validatedSource;
            try
            {
                validatedSource = File.Exists(path) ? File.ReadAllText(path) : null;
            }
            catch (Exception exception) when (exception is IOException ||
                                               exception is UnauthorizedAccessException)
            {
                errors.Add("Cannot read existing generated source: " + exception.Message);
                return false;
            }
            if (validatedSource != null)
            {
                // Never overwrite hand-authored scripts by accident.
                using (StringReader reader = new StringReader(validatedSource))
                {
                    if (reader.ReadLine() != GeneratedHeader)
                    {
                        errors.Add("Refusing to overwrite a non-generated file: " + path);
                        return false;
                    }
                }
            }

            // Unlike a blind overwrite, explicit manual regeneration also checks
            // whether the previously generated source was modified outside Advanced UI Toolkit.
            if (File.Exists(path) && existingRoot != null && existingRoot.EditorHasGenerationProfile)
            {
                existingRoot.EditorGetGenerationProfile(out string savedClass,
                    out string savedNamespace, out string savedFolder);
                string savedTemplate = existingRoot.EditorGetGenerationTemplatePath();
                if (!string.IsNullOrEmpty(savedTemplate) &&
                    AssetDatabase.LoadAssetAtPath<MonoScript>(savedTemplate) == null)
                {
                    errors.Add("The previous generation template is missing: " + savedTemplate +
                               ". Restore it before overwriting generated code.");
                    return false;
                }
                string expectedPrevious;
                try
                {
                    expectedPrevious = AdvancedUIToolkitCodeTemplate.Generate(savedClass, savedNamespace,
                        existingRoot.EditorGetEntries().Where(e => e != null).ToList(), savedTemplate);
                }
                catch (Exception exception)
                {
                    errors.Add("Unable to validate the existing generated file: " + exception.Message);
                    return false;
                }
                if (!string.Equals(validatedSource, expectedPrevious, StringComparison.Ordinal))
                {
                    if (!interactive || !EditorUtility.DisplayDialog(
                        "Advanced UI Toolkit - Generated source changed",
                        "This generated C# file differs from the version expected from the saved manifest. " +
                        "Manual edits will be lost if you overwrite it. Continue deliberately?\n\n" + path,
                        "Overwrite Generated File", "Cancel"))
                    {
                        errors.Add("Generated file contains unexpected changes. Review it before overwriting: " + path);
                        return false;
                    }
                }
            }

            bool breaking = removed.Count > 0 || candidates.Any(c =>
                !string.IsNullOrEmpty(c.PreviousKey) && c.ApiKey != c.PreviousKey);
            if (breaking && !interactive && !(allowRemovedAccessors &&
                !candidates.Any(c => !string.IsNullOrEmpty(c.PreviousKey) && c.ApiKey != c.PreviousKey)))
            {
                errors.Add("Breaking accessor changes require manual review.");
                return false;
            }
            if (breaking && interactive && !EditorUtility.DisplayDialog(
                "Advanced UI Toolkit - Breaking API changes",
                "The preview contains removed or renamed generated properties. " +
                "Your existing scripts may need to be updated after regeneration. Continue?",
                "Generate", "Cancel"))
                return false;

            // Stage source writes before touching serialized manifest data. A failed
            // file operation must leave the existing UI root references untouched.
            List<UIBindingRoot.Entry> manifest = new List<UIBindingRoot.Entry>(candidates.Count);
            foreach (BindingCandidate candidate in candidates.OrderBy(c => c.ApiKey, StringComparer.Ordinal))
            {
                manifest.Add(new UIBindingRoot.Entry
                {
                    Key = candidate.ApiKey,
                    HierarchyKey = candidate.HierarchyKey,
                    StableId = candidate.StableId,
                    ComponentType = candidate.ComponentType,
                    XmlSummary = candidate.XmlSummary,
                    Reference = candidate.Reference
                });
            }

            string source;
            try
            {
                source = BuildGeneratedSource(manifest);
            }
            catch (Exception exception)
            {
                errors.Add("Cannot render generated source: " + exception.Message);
                return false;
            }

            // Remember the current manifest and generation profile before committing.
            // Both the C# file and these values must be restored if either update fails.
            List<UIBindingRoot.Entry> previousEntries = existingRoot != null
                ? existingRoot.EditorGetEntries().ToList() : null;
            string previousClass = null;
            string previousNamespace = null;
            string previousFolder = null;
            string previousTemplate = null;
            if (existingRoot != null)
            {
                existingRoot.EditorGetGenerationProfile(out previousClass,
                    out previousNamespace, out previousFolder);
                previousTemplate = existingRoot.EditorGetGenerationTemplatePath();
            }

            bool requiresWrite;
            try
            {
                requiresWrite = AdvancedUIToolkitGenerationTransaction.WriteAndCommit(
                    path, validatedSource, source, () =>
                    {
                        UIBindingRoot root = target.GetComponent<UIBindingRoot>();
                        bool created = root == null;
                        try
                        {
                            if (created) root = target.AddComponent<UIBindingRoot>();
                            PersistDerivedManifest(target, root, manifest, className,
                                namespaceName, outputFolder, exampleScript != null
                                    ? AssetDatabase.GetAssetPath(exampleScript) : string.Empty);
                        }
                        catch
                        {
                            // Generated C# will be rolled back by WriteAndCommit.
                            // Put the serialized metadata back as well, without adding
                            // an Undo operation to the user's Hierarchy history.
                            if (created)
                            {
                                if (root != null) DestroyImmediate(root);
                            }
                            else
                            {
                                root.EditorSetEntries(previousEntries);
                                root.EditorSetGenerationProfile(previousClass,
                                    previousNamespace, previousFolder);
                                root.EditorSetGenerationTemplatePath(previousTemplate);
                                EditorUtility.SetDirty(root);
                            }
                            throw;
                        }
                    });
            }
            catch (Exception exception)
            {
                errors.Add("Cannot commit generated C# and binding manifest: " +
                    exception.Message + " Review the error and retry after rescanning.");
                return false;
            }

            if (requiresWrite)
                AssetDatabase.ImportAsset(path);

            Debug.Log($"Advanced UI Toolkit: Updated {manifest.Count} bindings in {path}. " +
                "Save your scene/prefab to persist the manifest.", target);
            if (interactive) Scan();
            return true;
        }

        /// <summary>
        /// Persists generated binding data without registering a Unity Undo operation.
        /// Generated C# files cannot participate in Unity Undo, so registering a manifest
        /// change would split a delete/restore sequence into mismatched undo steps.
        /// The scene is still marked dirty so the derived manifest can be saved.
        /// </summary>
        /// <param name="owner">The GameObject owning the binding manifest.</param>
        /// <param name="root">The component that stores serialized binding entries.</param>
        /// <param name="manifest">The newly validated entries.</param>
        /// <param name="generatedClassName">Generated class name.</param>
        /// <param name="generatedNamespace">Namespace containing the generated class.</param>
        /// <param name="generatedOutputFolder">Directory for generated C# source.</param>
        /// <param name="generatedTemplatePath">Optional source template path.</param>
        internal static void PersistDerivedManifest(GameObject owner, UIBindingRoot root,
            List<UIBindingRoot.Entry> manifest, string generatedClassName,
            string generatedNamespace, string generatedOutputFolder,
            string generatedTemplatePath)
        {
            if (owner == null) throw new ArgumentNullException(nameof(owner));
            if (root == null) throw new ArgumentNullException(nameof(root));

            root.EditorSetEntries(manifest);
            root.EditorSetGenerationProfile(generatedClassName, generatedNamespace,
                generatedOutputFolder);
            root.EditorSetGenerationTemplatePath(generatedTemplatePath);
            EditorUtility.SetDirty(root);
            if (PrefabUtility.IsPartOfPrefabInstance(root))
                PrefabUtility.RecordPrefabInstancePropertyModifications(root);
            if (owner.scene.IsValid())
                EditorSceneManager.MarkSceneDirty(owner.scene);
        }

        /// <summary>Determines whether safe output folder.</summary>
        private static bool IsSafeOutputFolder(string folder)
        {
            if (string.IsNullOrWhiteSpace(folder) ||
                !folder.StartsWith("Assets/", StringComparison.Ordinal) ||
                folder.Contains(":") || folder.Contains("//") || folder.Contains(".."))
                return false;

            string projectRoot = System.IO.Path.GetFullPath(System.IO.Path.Combine(
                UnityEngine.Application.dataPath, ".."));
            string assetsRoot = System.IO.Path.GetFullPath(UnityEngine.Application.dataPath)
                .TrimEnd(System.IO.Path.DirectorySeparatorChar) + System.IO.Path.DirectorySeparatorChar;
            string candidate = System.IO.Path.GetFullPath(System.IO.Path.Combine(
                projectRoot, folder));
            return candidate.StartsWith(assetsRoot, StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>Builds documented C# bindings using the selected template or default layout.</summary>
        /// <param name="manifest">The references to expose as generated properties.</param>
        /// <returns>A complete C# source file with the auto-generated safety header.</returns>
        private string BuildGeneratedSource(List<UIBindingRoot.Entry> manifest)
        {
            string templatePath = exampleScript != null
                ? AssetDatabase.GetAssetPath(exampleScript) : string.Empty;
            return AdvancedUIToolkitCodeTemplate.Generate(className, namespaceName, manifest, templatePath);
        }

