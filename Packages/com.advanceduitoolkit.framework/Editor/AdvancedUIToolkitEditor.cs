    }

    /// <summary>Scans named uGUI components, validates their references, and generates typed bindings.</summary>
    public sealed class UIAutoBinderWindow : EditorWindow
    {
        /// <summary>Stores the binding candidate reference or configuration value.</summary>
        private sealed class BindingCandidate
        {
            /// <summary>Stores the stable id reference or configuration value.</summary>
            public string StableId;
            /// <summary>Stores the previous key reference or configuration value.</summary>
            public string PreviousKey;
            /// <summary>The last saved name-derived key, before a hierarchy rename.</summary>
            public string PreviousHierarchyKey;
            /// <summary>Stores the hierarchy key reference or configuration value.</summary>
            public string HierarchyKey;
            /// <summary>Stores the api key reference or configuration value.</summary>
            public string ApiKey;
            /// <summary>Stores the component type reference or configuration value.</summary>
            public string ComponentType;
            /// <summary>Stores the reference reference or configuration value.</summary>
            public Component Reference;
        }

        /// <summary>Defines the preserve pref constant.</summary>
        private const string PreservePref = "AdvancedUIToolkit.AutoBinder.PreserveApiOnRename";
        /// <summary>Defines the generated header constant.</summary>
        private const string GeneratedHeader = "// <auto-generated />";
        /// <summary>Stores the types reference or configuration value.</summary>
        private static readonly Dictionary<string, Type> Types = AdvancedUIToolkitNaming.TypeByPrefix;

        /// <summary>Stores the target reference or configuration value.</summary>
        private GameObject target;
        /// <summary>Stores the candidates reference or configuration value.</summary>
        private readonly List<BindingCandidate> candidates = new List<BindingCandidate>();
        /// <summary>Stores the removed reference or configuration value.</summary>
        private readonly List<UIBindingRoot.Entry> removed = new List<UIBindingRoot.Entry>();
        /// <summary>Stores the errors reference or configuration value.</summary>
        private readonly List<string> errors = new List<string>();
        /// <summary>Stores the warnings reference or configuration value.</summary>
        private readonly List<string> warnings = new List<string>();
        /// <summary>Stores the scroll reference or configuration value.</summary>
        private Vector2 scroll;
        /// <summary>Stores the class name reference or configuration value.</summary>
        private string className = "ScreenBindings";
        /// <summary>Stores the namespace name reference or configuration value.</summary>
        private string namespaceName = "Game.UI.Generated";
        /// <summary>Stores the output folder reference or configuration value.</summary>
        private string outputFolder = "Assets/AdvancedUIToolkit/Generated";
        /// <summary>Optional user-authored C# file defining the generated class structure.</summary>
        private MonoScript exampleScript;
        /// <summary>Stores the scan fingerprint reference or configuration value.</summary>
        private string scanFingerprint;
        /// <summary>Stores the preserve existing api reference or configuration value.</summary>
        private bool preserveExistingApi = true;
        /// <summary>Stores the anual key overrides reference or configuration value.</summary>
        private bool manualKeyOverrides;

        /// <summary>Opens value.</summary>
        public static void Open() => AdvancedUIToolkitWorkspaceWindow.OpenTab(AdvancedUIToolkitWorkspaceWindow.WorkspaceTab.Bindings);

        /// <summary>Opens for.</summary>
